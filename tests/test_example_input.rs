use day_7::*;

#[test]
fn test_example_input() {
    let input = "
        .......S.......
        ...............
        .......^.......
        ...............
        ......^.^......
        ...............
        .....^.^.^.....
        ...............
        ....^.^...^....
        ...............
        ...^.^...^.^...
        ...............
        ..^...^.....^..
        ...............
        .^.^.^.^.^...^.
        ...............
    ";

    let manifold = parse_manifold(input.to_string());
    let result   = trace_tachyon(manifold);

    assert_eq!(result, 21);
}

