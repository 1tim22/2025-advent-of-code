use day_4::*;

#[test]
fn test_example_input() {

    let table = parse_input("
        ..@@.@@@@.
        @@@.@.@.@@
        @@@@@.@.@@
        @.@@@@..@.
        @@.@@@@.@@
        .@@@@@@@.@
        .@.@.@.@@@
        @.@@@.@@@@
        .@@@@@@@@.
        @.@.@@@.@.
    ".to_string());

    let result = window(table);

    assert_eq!(result, 13);
}

#[test]
fn test_example_modified_input() {

    let table = parse_input("
        ..@@.@@@@.@@@.@.@.@@
        @@@@@.@.@@@.@@@@..@.
        @@.@@@@.@@.@@@@@@@.@
    ".to_string());

    let result = window(table);

    assert_eq!(result, 17);
}

